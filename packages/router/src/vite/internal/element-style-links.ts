/**
 * alpha15 S lane — the SSR half of the element runtime's component-stylesheet
 * seam.
 *
 * Element's `internal/compiled/server/style-links.ts` holds the URLs a server
 * process declares and reads them when serializing a DSD template. The
 * generated SSR/SSG entry imports {@linkcode STYLE_LINKS_VIRTUAL_ID}; this
 * plugin answers that import with a module that hands the build's emitted
 * addresses to the runtime setter. One mechanism carries every build-time-known
 * address (the same shape `__setRequestTimeClientScript` uses), the value is
 * bundled into `dist/server/index.js` so the deployed request-time server
 * re-applies it at startup, and client/dev builds simply never import the
 * module — their roots take the registered constructable sheet instead.
 */

import type { Plugin } from 'vite';

/** The import specifier the generated SSR/SSG entry carries. */
export const STYLE_LINKS_VIRTUAL_ID = 'virtual:open-element-style-links' as const;

/** The `\0`-virtual graph id behind the specifier. */
const STYLE_LINKS_GRAPH_ID = '\0open-element-style-links.js';

/**
 * The plugin that answers {@linkcode STYLE_LINKS_VIRTUAL_ID} with the build's
 * emitted component stylesheet URLs. Always added to the SSG/SSR build (the
 * generated entry always imports it); an app with no component stylesheet
 * writes the empty list, which is the runtime's documented no-link state.
 */
export function elementStyleLinksPlugin(urls: readonly string[]): Plugin {
  return {
    name: 'open:element-style-links',
    resolveId(id) {
      return id === STYLE_LINKS_VIRTUAL_ID ? STYLE_LINKS_GRAPH_ID : null;
    },
    load(id) {
      if (id !== STYLE_LINKS_GRAPH_ID) return null;
      return [
        '// <generated by open:element-style-links — component stylesheet URLs; do not edit>',
        "import { __setRequestTimeStyleSheetUrls } from '@openelement/element';",
        `__setRequestTimeStyleSheetUrls(${JSON.stringify(urls)});`,
        '',
      ].join('\n');
    },
  };
}
