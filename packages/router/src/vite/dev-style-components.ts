/**
 * The dev channel of the component stylesheet (alpha15 S lane S5-A, provider
 * port stage 2B).
 *
 * Production delivers the shadow utilities as a content-addressed client asset
 * (Phase 2) plus a declarative `<link>` in every DSD template. Dev has no
 * client build, so this plugin supplies the same three facts from the dev
 * server, through the same protocol and without any inline CSS or runtime DOM
 * write:
 *
 * 1. The sheet itself is served at the stable dev URL
 *    `<base>.openElement/<engine>-components.current.css`, compiled through
 *    the SELECTED provider's public API from the same candidate set the build
 *    uses (one engine, one candidate channel, one sheet).
 * 2. The generated dev SSR entry imports `virtual:open-element-style-links`;
 *    this plugin answers that import with the dev URL, so every DSD template
 *    of a component whose classes were admitted declares the resource.
 * 3. The client's shared sheet comes from the adapter module behind the
 *    provider's own component-sheet specifier: one `CSSStyleSheet` per realm
 *    held on `globalThis`, filled by `fetch` + `replace()`, carrying the
 *    protocol's readiness and identity keys. The object survives HMR
 *    re-evaluation, so an edit UPDATES the same sheet (every root holding it
 *    re-renders) instead of replacing the reference.
 *
 * HMR: a `.tsx` edit can change the admitted candidate set and a declared
 * theme source edit changes the theme layer. Both dirty the compile cache; the
 * watcher re-registers the module's facts and only then invalidates the adapter
 * module — Vite then re-fetches the sheet through the adapter's
 * `import.meta.hot.accept`, so connected shadow roots update in place. No node
 * is created, no page reload is required for the stylesheet half of the
 * change.
 *
 * PROVIDER SELECTION IS STATIC: the plan names one engine, the integration for
 * that engine is constructed here, and the other engine's package is never
 * imported by this dev server.
 */

import process from 'node:process';
import type { Plugin, ViteDevServer } from 'vite';
import { createLogger } from '@openelement/element';
import { collectShadowClassCandidates } from './internal/collect-shadow-candidates.ts';
import { STYLE_LINKS_VIRTUAL_ID } from './internal/element-style-links.ts';
import type { DevStyleSession } from './internal/dev-style-session.ts';
import { reportRecoveryFailure } from './internal/build-diagnostics.ts';
import { devClientModulePath } from './internal/dev-client-path.ts';
import type { OpenPluginState } from './plugin-config.ts';

const log = createLogger('router-vite:style-components-dev');

/**
 * The public dev URL of the served component stylesheet.
 *
 * Dev-only detail: the URL is ONE stable resource
 * (`…/<engine>-components.current.css`), not a versioned one. The DSD link is
 * baked into the served HTML when a page renders, and the client adapter is
 * served later; a version derived from the candidate set is sampled at both
 * moments and the set is not complete until the app's own shadow modules have
 * been transformed — so the two samples legitimately disagree and the client's
 * fail-closed resource check rejects its own server's link. Identity must be a
 * fact both halves can state, and in dev that fact is the one sheet the dev
 * server compiles. Freshness rides the other two seams instead: the response
 * is `no-store` (compiled per request), and a content-moving change
 * re-evaluates the client adapter through its own hot-accept, which refills
 * the same `CSSStyleSheet`. Production keeps its single content-addressed
 * asset — the dev URL is not part of the built contract.
 */
export function devComponentSheetUrl(base: string, engine: string, version = 'current'): string {
  const cleanBase = base.endsWith('/') ? base : `${base}/`;
  return `${cleanBase}.openElement/${engine}-components.${version}.css`;
}

/** The generated dev adapter module for the shared component sheet. */
function devSheetAdapterModule(url: string): string {
  return [
    '// <generated by open:style-components-dev — dev sheet adapter; do not edit>',
    '// One CSSStyleSheet per realm, held on globalThis so an HMR re-evaluation',
    '// UPDATES the same object (every root holding it re-renders) instead of',
    '// handing out a fresh reference. Fetch + replace() — no DOM node, ever.',
    `const sheetUrl = ${JSON.stringify(url)};`,
    'const holder = (globalThis.__openElementComponentSheet ??= { sheet: new CSSStyleSheet(), url: sheetUrl });',
    'const sheet = holder.sheet;',
    "const ready = fetch(sheetUrl, { headers: { accept: 'text/css,*/*;q=0.1' } })",
    '  .then((response) => {',
    '    if (!response.ok) {',
    `      throw new Error('[openElement] component stylesheet request failed with ' + response.status + ': ' + sheetUrl);`,
    '    }',
    '    return response.text();',
    '  })',
    '  .then((css) => sheet.replace(css));',
    '// Observed without conversion: the stored promise keeps its rejected state.',
    'void ready.catch(() => {});',
    "sheet['__openElementStyleReady'] = ready;",
    "sheet['__openElementStyleSheetUrl'] = sheetUrl;",
    'export default sheet;',
    'if (import.meta.hot) import.meta.hot.accept(() => { /* re-evaluated: the fetch above re-fills the same sheet object */ });',
    '',
  ].join('\n');
}

export function devStyleComponentsPlugin(state: OpenPluginState, session: DevStyleSession): Plugin {
  let root = process.cwd();
  let base = '/';
  const styleLinksId = '\0open-element-style-links-dev.js';
  const adapterId = '\0oe-style-components-dev.js';
  const engine = (): string => session.current()?.provider.id ?? 'style';
  const currentCss = async (): Promise<string> => {
    const provider = session.current()?.provider;
    if (provider === undefined) return '';
    // Always compile for the CURRENT candidate set and the CURRENT generator,
    // never from a cache: the served URL is stable by design (see the URL's
    // note), so the response is the only place the compiled sheet can be
    // fresh — including after the engine's configuration has been rebuilt.
    return await provider.compileComponents({
      candidates: state.classCandidates.all(),
      sources: new Map(),
    });
  };
  /** A change that may move the admitted candidates or the theme layer. */
  const relevantChange = (file: string): boolean =>
    /\.(?:tsx|css)$/.test(file) ||
    (session.current()?.plan.theme ?? []).some((source) => file.endsWith(source));

  return {
    name: 'open:style-components-dev',
    apply: 'serve',
    enforce: 'pre',

    configResolved(config) {
      root = config.root ?? process.cwd();
      base = config.base ?? '/';
      session.setRoot(root);
    },

    async configureServer(server: ViteDevServer) {
      const resolved = await session.resolve();
      if (resolved === undefined) return;
      session.attach(server);
      // The sheet's own endpoint: a direct `text/css` response, compiled per
      // request from the current candidate set. Registered before Vite's
      // internal middlewares, so neither the module graph nor the CSS plugin
      // ever sees this URL.
      server.middlewares.use(async (request, response, next) => {
        const url = request.url ?? '';
        const path = url.split('?', 1)[0];
        if (
          path === undefined ||
          !/\.openElement\/[a-z0-9-]+-components\.[^./]+\.css$/.test(path)
        ) {
          next();
          return;
        }
        try {
          const css = await currentCss();
          response.statusCode = 200;
          response.setHeader('Content-Type', 'text/css; charset=utf-8');
          response.setHeader('Cache-Control', 'no-store');
          response.end(css);
        } catch (error) {
          response.statusCode = 500;
          response.setHeader('Content-Type', 'text/plain; charset=utf-8');
          response.end(
            `[openElement] component stylesheet compile failed: ${
              error instanceof Error ? error.message : String(error)
            }`,
          );
        }
      });
      log.info(
        `${engine()} component sheet served at ${devComponentSheetUrl(base, engine(), 'current')} ` +
          '(compiled by the engine’s own API, adopted as one shared CSSStyleSheet)',
      );
      /**
       * Everything that must follow a registration change: the client adapter
       * (when loaded) is re-evaluated in place, so it refetches the stable
       * sheet URL and replaces the same `CSSStyleSheet` object. The sheet
       * response itself is compiled per request, so there is nothing to
       * invalidate on the server half.
       */
      const afterCandidatesMoved = (): void => {
        // The candidate set (or a declared theme source) may have moved: hand
        // the client modules their update. The browser refetches through the
        // adapter's hot-accept, so the sheet object is re-filled in place — no
        // new nodes, no page reload for the stylesheet half of the change. The
        // update is sent only AFTER the registration completed, so the client
        // can never refetch a sheet built from the old facts.
        //
        // The shared sheet's adapter is a CLIENT module: re-evaluate it (its
        // hot-accept refetches and `replace()`s the same sheet object) — but
        // only when the page actually loaded it. Sending an update for a
        // module the client does not know makes Vite fall back to a full
        // reload, which this lane must never be the cause of.
        const clientGraph = server.environments.client.moduleGraph;
        const adapter = clientGraph.idToModuleMap.get(adapterId);
        if (adapter !== undefined) {
          const url = devClientModulePath(adapter);
          clientGraph.invalidateModule(adapter);
          if (url !== undefined) {
            server.environments.client.hot.send({
              type: 'update',
              updates: [
                {
                  type: 'js-update',
                  path: url,
                  acceptedPath: url,
                  timestamp: Date.now(),
                },
              ],
            });
          }
        }
      };
      /**
       * A watched file's change/add: re-register the module's CURRENT
       * candidates and only then move the served version.
       *
       * The registration is awaited, not detached: the SSR module graph may not
       * have re-transformed the module yet, and bumping the version before the
       * new facts are registered would serve a sheet compiled from the old ones
       * (the ordering defect C names). Failures are reported, never swallowed —
       * a silently unregistered edit would leave the served sheet stale.
       */
      const onFile = async (file: string): Promise<void> => {
        if (!relevantChange(file)) return;
        if (/\.tsx$/.test(file)) {
          // The compile is the same engine the transform runs (one module, not
          // the whole app).
          await collectShadowClassCandidates({
            root,
            modules: [{ path: file }],
            candidates: state.classCandidates,
          });
        }
        afterCandidatesMoved();
      };
      /**
       * A watched file's deletion: the module left the graph, so its facts must
       * leave the registry too — otherwise the deleted component's classes keep
       * shipping in every subsequent sheet.
       */
      const onUnlink = (file: string): void => {
        if (!relevantChange(file)) return;
        state.classCandidates.remove(file);
        afterCandidatesMoved();
      };
      // The engine's configuration moved: the session rebuilt the generator,
      // and the sheet the client already holds was compiled from the old one —
      // re-evaluate the adapter so it refetches the stable URL and replaces the
      // same `CSSStyleSheet`.
      session.onConfigurationChange(afterCandidatesMoved);
      server.watcher.on('change', (file) => {
        void onFile(file).catch((error) => {
          reportRecoveryFailure(
            log,
            `${engine()} component sheet: re-registering ${file} failed — the served sheet ` +
              `keeps the previous facts`,
            error,
          );
        });
      });
      server.watcher.on('add', (file) => {
        void onFile(file).catch((error) => {
          reportRecoveryFailure(
            log,
            `${engine()} component sheet: registering ${file} failed — the served sheet ` +
              `keeps the previous facts`,
            error,
          );
        });
      });
      server.watcher.on('unlink', onUnlink);
    },

    resolveId(id) {
      const current = session.current();
      if (current === undefined) return null;
      // The sheet never enters Vite's module graph: it is served as a plain
      // `text/css` response (see the middleware above). A CSS-typed module id
      // would make Vite wrap the sheet in its dev style-injector, which writes
      // a <style> node at runtime — exactly what this lane forbids.
      if (id === current.provider.componentSheetSpecifier) return adapterId;
      if (id === STYLE_LINKS_VIRTUAL_ID) return styleLinksId;
      return null;
    },

    load(id) {
      const current = session.current();
      if (current === undefined) return null;
      if (id === styleLinksId) {
        return [
          '// <generated by open:style-components-dev — dev sheet URLs; do not edit>',
          "import { __setRequestTimeStyleSheetUrls } from '@openelement/element';",
          `__setRequestTimeStyleSheetUrls(${JSON.stringify([
            devComponentSheetUrl(base, engine()),
          ])});`,
          '',
        ].join('\n');
      }
      if (id === adapterId) {
        return devSheetAdapterModule(devComponentSheetUrl(base, engine()));
      }
      return null;
    },
  };
}
